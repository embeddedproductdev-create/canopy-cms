import fs from 'fs'
import path from 'path'
import { DatabaseSync } from 'node:sqlite'

type Row = Record<string, unknown>

const useLocal = process.argv.includes('--local')
const db = (() => {
  if (useLocal) {
    const dir = path.resolve('.wrangler/state/v3/d1/miniflare-D1DatabaseObject')
    const file = fs
      .readdirSync(dir)
      .filter((f) => f.endsWith('.sqlite'))
      .map((f) => path.join(dir, f))
      .sort((a, b) => fs.statSync(b).size - fs.statSync(a).size)[0]
    return new DatabaseSync(file, { readOnly: true })
  }
  const memory = new DatabaseSync(':memory:')
  memory.exec(fs.readFileSync(path.resolve('seed/db-dump.sql'), 'utf8'))
  return memory
})()

const all = (query: string, ...params: (string | number)[]): Row[] => db.prepare(query).all(...params) as Row[]
const cut = (value: unknown, length = 90): string => String(value ?? '').replace(/\s+/g, ' ').trim().slice(0, length)

const KINDS: Record<string, string> = { stat: 'stat', breadcrumb: 'breadcrumb', field: 'form field', link: 'link', empty: 'empty slot' }
const out: string[] = []

function cardLine(card: Row): string {
  const kind = card.type ? ` _(${KINDS[String(card.type)] ?? card.type})_` : ''
  const detail = cut(card.short_description || card.subheading || card.value || card.tags, 80)
  return `    - ${cut(card.title, 70)}${kind}${detail ? ` - ${detail}` : ''}`
}

function sectionBlock(owner: string, id: number): string[] {
  const lines: string[] = []
  const sections = all(
    `SELECT s.* FROM ${owner}_rels r JOIN section s ON s.id = r.section_id WHERE r.parent_id = ? AND r.path = 'layoutSections' ORDER BY r."order"`,
    id,
  )
  if (!sections.length) return ['  - _no sections_']
  for (const section of sections) {
    const variant = section.variant ? ` ${section.variant}` : ''
    const hidden = section.hidden ? ' **hidden**' : ''
    lines.push(`  - **${cut(section.type)}${variant}**${hidden} - ${cut(section.title, 70)}${section.heading ? `: "${cut(section.heading, 70)}"` : ''}`)
    const cards = all(`SELECT c.* FROM section_rels r JOIN card c ON c.id = r.card_id WHERE r.parent_id = ? ORDER BY r."order"`, Number(section.id))
    for (const card of cards) lines.push(cardLine(card))
  }
  return lines
}

out.push(
  '# Content map',
  '',
  `Generated by \`npm run docs:content${useLocal ? ' -- --local' : ''}\` from ${useLocal ? 'the local database' : '`seed/db-dump.sql`'}. It shows how every document is built: **Page / Collection document -> Section -> Card**.`,
  '',
  '## Pages',
  '',
)
for (const page of all(`SELECT * FROM page ORDER BY id`)) {
  out.push(`### ${cut(page.title)} (\`${page.url}\`)`, '', `Identity: heading "${cut(page.heading, 80)}"${page.page_type ? `, type ${page.page_type}` : ''}`, '', ...sectionBlock('page', Number(page.id)), '')
}

const collections: { title: string; table: string; label: string; identity: (row: Row) => string }[] = [
  { title: 'Capabilities', table: 'capability', label: 'capability', identity: (r) => `slug \`${r.slug}\`, summary "${cut(r.summary, 80)}"` },
  { title: 'Industries', table: 'industry', label: 'industry', identity: (r) => `slug \`${r.slug}\`, summary "${cut(r.summary, 80)}"` },
  { title: 'Portfolio', table: 'case_study', label: 'project', identity: (r) => `slug \`${r.slug}\`, ${r.category}, stage ${r.project_stage}${r.featured ? ', featured' : ''}` },
  { title: 'Insights', table: 'blog', label: 'insight', identity: (r) => `slug \`${r.slug}\`, ${r.category}, published ${cut(r.published_date, 10)}${r.featured ? ', featured' : ''}` },
  { title: 'Checklists', table: 'checklist', label: 'checklist', identity: (r) => `slug \`${r.slug}\`, ${all(`SELECT count(*) n FROM checklist_items WHERE _parent_id = ${Number(r.id)}`)[0].n} items (${r.locked_items_count} locked)` },
]
for (const collection of collections) {
  out.push(`## ${collection.title}`, '')
  for (const doc of all(`SELECT * FROM ${collection.table} ORDER BY id`)) {
    out.push(`### ${cut(doc.title)}`, '', `Identity: ${collection.identity(doc)}`, '')
    out.push(...(collection.table === 'checklist' && !all(`SELECT 1 FROM checklist_rels WHERE parent_id = ${Number(doc.id)}`).length ? ['  - _no extra sections_'] : sectionBlock(collection.table, Number(doc.id))), '')
  }
}

const media = all('SELECT filename, alt FROM media ORDER BY id')
out.push('## Media', '', `${media.length} files, each with its alt text.`, '', ...media.map((m) => `- ${m.filename} - ${cut(m.alt, 70)}`), '')

fs.writeFileSync(path.resolve('CONTENT-MAP.md'), out.join('\n'))
console.log(`CONTENT-MAP.md written (${out.length} lines)`)
